GRANT SELECT ON TFM.VMV_TFM_ROAD TO FSA_LRM_READ_WRITE_ROLE;
GRANT SELECT ON TFM.V_LRM_CBR_EXPORT TO FSA_LRM_READ_WRITE_ROLE;

