-- SELECT-only access for the CBR team's LRMOPS API.
--   Road search and road lookup: TFM_ROAD, VMV_TFM_ROAD, and the code tables their columns reference.
--   A CBR site's LRMOPS details: V_LRM_CBR_EXPORT (the source of CBR's THE.V_LRM_CBR_EXPORT).
--   Road details at a location (the logic of V_TFM_QB_CBR_EXPORT): the bridge features, and the
--   road type, responsibility and road use permit events along a road.
